from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from app.db.session import get_db
from app.dependencies.auth import get_current_user
from app.models.user import User
from app.repositories.notification_repository import (
    NotificationPreferenceRepository,
    NotificationRepository,
)
from app.schemas.notification import (
    NotificationCategory,
    NotificationListResponse,
    NotificationPreferenceResponse,
    NotificationPreferenceUpdate,
    NotificationResponse,
    NotificationType,
    UnreadCountResponse,
)
from app.services.notification_service import NotificationService

router = APIRouter(
    prefix="/notifications",
    tags=["Notifications"],
)


def get_notification_service(db: Session = Depends(get_db)) -> NotificationService:
    repo = NotificationRepository(db)
    pref_repo = NotificationPreferenceRepository(db)
    return NotificationService(repo, pref_repo)


@router.get("", response_model=NotificationListResponse)
def get_notifications(
    limit: int = Query(50, ge=1, le=100),
    offset: int = Query(0, ge=0),
    unread_only: bool = Query(False),
    category: str | None = Query(None),
    current_user: User = Depends(get_current_user),
    service: NotificationService = Depends(get_notification_service),
):
    """
    List notifications for the current authenticated user with pagination and filters.
    """
    items, total = service.get_user_notifications(
        user_id=current_user.id,
        limit=limit,
        offset=offset,
        unread_only=unread_only,
        category=category,
    )
    unread_count = service.get_unread_count(current_user.id)
    return NotificationListResponse(
        items=[NotificationResponse.model_validate(n) for n in items],
        total=total,
        unread_count=unread_count,
    )


@router.get("/unread-count", response_model=UnreadCountResponse)
def get_unread_count(
    current_user: User = Depends(get_current_user),
    service: NotificationService = Depends(get_notification_service),
):
    """
    Get lightweight unread notification count for the authenticated user.
    """
    count = service.get_unread_count(current_user.id)
    return UnreadCountResponse(unread_count=count)


@router.patch("/{notification_id}/read", response_model=NotificationResponse)
def mark_notification_as_read(
    notification_id: UUID,
    current_user: User = Depends(get_current_user),
    service: NotificationService = Depends(get_notification_service),
):
    """
    Mark a single notification as read.
    """
    notification = service.mark_as_read(notification_id, current_user.id)
    if not notification:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Notification not found.",
        )
    return NotificationResponse.model_validate(notification)


@router.post("/read-all")
def mark_all_as_read(
    current_user: User = Depends(get_current_user),
    service: NotificationService = Depends(get_notification_service),
):
    """
    Mark all unread notifications as read for current user.
    """
    updated_count = service.mark_all_as_read(current_user.id)
    return {"updated_count": updated_count}


@router.delete("/{notification_id}")
def delete_notification(
    notification_id: UUID,
    current_user: User = Depends(get_current_user),
    service: NotificationService = Depends(get_notification_service),
):
    """
    Delete / dismiss a notification.
    """
    success = service.delete_notification(notification_id, current_user.id)
    if not success:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Notification not found.",
        )
    return {"success": True}


@router.get("/preferences", response_model=NotificationPreferenceResponse)
def get_preferences(
    current_user: User = Depends(get_current_user),
    service: NotificationService = Depends(get_notification_service),
):
    """
    Get user notification preferences.
    """
    return service.get_preferences(current_user.id)


@router.patch("/preferences", response_model=NotificationPreferenceResponse)
def update_preferences(
    updates: NotificationPreferenceUpdate,
    current_user: User = Depends(get_current_user),
    service: NotificationService = Depends(get_notification_service),
):
    """
    Update user notification preferences.
    """
    return service.update_preferences(current_user.id, updates)


@router.post("/test", response_model=NotificationResponse)
def create_test_notification(
    category: str = Query(NotificationCategory.COLLABORATION),
    title: str = Query("Test Notification"),
    message: str = Query("This is a test notification generated by MindVault."),
    current_user: User = Depends(get_current_user),
    service: NotificationService = Depends(get_notification_service),
):
    """
    Test endpoint for developer and automated verification.
    """
    notification = service.create_notification(
        user_id=current_user.id,
        type=NotificationType.SYSTEM_NOTICE,
        category=category,
        title=title,
        message=message,
    )
    if not notification:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Notification was suppressed by user preferences.",
        )
    return NotificationResponse.model_validate(notification)
